const PACKS: Record<string, Partial<Record<UiKey, string>>> = {
  "en-IN": EN,
  "hi-IN": HI,
  "gu-IN": GU,
  "mr-IN": MR,
  "bn-IN": BN,
  "ta-IN": TA,
  "te-IN": TE,
  "kn-IN": KN,
  "ml-IN": ML,
  "pa-IN": PA,
  "or-IN": OR,
  "ur-IN": UR,
};

function packFor(lang: string): Partial<Record<UiKey, string>> {
  if (PACKS[lang]) return PACKS[lang];
  const short = lang.slice(0, 2);
  const hit = Object.entries(PACKS).find(([k]) => k.startsWith(short));
  return hit?.[1] ?? EN;
}

export function t(lang: string, key: UiKey, vars?: Vars) {
  const pack = packFor(lang);
  return fill(pack[key] ?? EN[key] ?? key, vars);
}

export function localeFor(lang: string) {
  return lang || "en-IN";
}

export function isRtl(lang: string) {
  return lang.startsWith("ur");
}

const INDUSTRY_KEYS: Record<Industry, UiKey> = {
  pharmaceutical: "pharmaceutical",
  grocery: "grocery",
  electrical: "electrical",
  hardware: "hardware",
  construction: "construction",
  electronics: "electronics",
  consumer: "consumer",
};

export function industryLabel(lang: string, id: Industry | "" | undefined) {
  if (!id) return t(lang, "tradeNotSet");
  return t(lang, INDUSTRY_KEYS[id] ?? "grocery");
}

const STATUS_KEYS: Record<string, UiKey> = {
  pending: "pending",
  sent: "sent",
  reviewing: "reviewing",
  quoted: "quoted",
  accepted: "acceptedStatus",
  confirmed: "confirmed",
  partial: "partialConfirmed",
  finalized: "finalized",
  delivered: "deliveredStatus",
  rejected: "rejectedStatus",
  order: "order",
  inquiry: "inquiry",
  draft: "draft",
};

export function statusLabel(lang: string, status: string) {
  const key = STATUS_KEYS[status];
  return key ? t(lang, key) : status;
}

export function useT() {
  const language = useVaani((s) => s.language || "en-IN");
  return {
    lang: language,
    t: (key: UiKey, vars?: Vars) => t(language, key, vars),
    industry: (id: Industry | "" | undefined) => industryLabel(language, id),
    status: (id: string) => statusLabel(language, id),
    locale: localeFor(language),
  };
}
